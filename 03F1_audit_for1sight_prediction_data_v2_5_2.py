"""
For1Sight V2.5.2 - Prediction Data Audit
READ-ONLY: no ETL, no HDFS writes, no API calls, no model training.

Run from the For1Sight project root:
    python .\audit_for1sight_prediction_data_v2_5_2.py

Optional PowerShell log:
    python .\audit_for1sight_prediction_data_v2_5_2.py *> .\prediction_data_audit_v2_5_2.log

The UTF-8 report is saved to:
    for1sight_warehouse\prediction_data_audit_v2_5_2.txt
"""

from __future__ import annotations

import json
import re
import sys
import traceback
from pathlib import Path
from datetime import datetime

# Make Windows PowerShell/console output tolerant of UTF-8 characters.
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass
try:
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

ROOT = Path(__file__).resolve().parent
WAREHOUSE = ROOT / "for1sight_warehouse"
HDFS = "hdfs://localhost:9000"
SILVER_LAPS = HDFS + "/for1sight_warehouse/silver/hf_laptimes"
RACE_FILES = [
    WAREHOUSE / "race_results_2024.json",
    WAREHOUSE / "race_results_2025.json",
    WAREHOUSE / "race_results_2026.json",
]
LOCAL_FILES = {
    "EXISTING QUALIFYING ML TRAINING TABLE": WAREHOUSE / "ml_training_table.parquet",
    "LOCAL CLEAN LAP TIMES": WAREHOUSE / "hf_laptimes_clean.parquet",
}
REPORT = []

def emit(message=""):
    line = str(message)
    REPORT.append(line)
    try:
        print(line)
    except UnicodeEncodeError:
        print(line.encode("ascii", errors="replace").decode("ascii"))

def section(title):
    emit("\n" + "=" * 88)
    emit(title)
    emit("=" * 88)

def normalize_event(value):
    value = str(value or "").lower().strip()
    value = re.sub(r"\bgrand\s*prix\b", "", value)
    return re.sub(r"[^a-z0-9]", "", value)

def extract_races(obj):
    if isinstance(obj, list):
        return obj
    if not isinstance(obj, dict):
        return []
    mr = obj.get("MRData") or obj.get("mrData") or {}
    rt = mr.get("RaceTable") or mr.get("raceTable") or {}
    races = rt.get("Races") or rt.get("races")
    if isinstance(races, list):
        return races
    for key in ("races", "Races", "results", "Results"):
        if isinstance(obj.get(key), list):
            return obj[key]
    return []

def inspect_local_parquet(label, path, spark):
    section(label)
    emit(f"Path: {path}")
    emit(f"Python path exists: {path.exists()}")
    if not path.exists():
        emit("STATUS: NOT FOUND by Python. Confirm this file/folder is present in for1sight_warehouse.")
        return

    # Prefer PyArrow for local Windows paths. This avoids Spark/Hadoop URI parsing
    # problems with drive letters and spaces in folder names.
    try:
        import pyarrow.dataset as ds
        dataset = ds.dataset(str(path), format="parquet")
        emit("Reader: PyArrow local filesystem")
        emit(f"Rows: {dataset.count_rows():,}")
        emit(f"Columns: {', '.join(dataset.schema.names)}")
        for field in dataset.schema:
            emit(f"  {field.name}: {field.type}")
        batch_iter = dataset.scanner(batch_size=5).to_batches()
        first = next(batch_iter, None)
        if first is not None:
            emit("Sample rows:")
            for row in first.slice(0, 5).to_pylist():
                emit("  " + json.dumps(row, default=str, ensure_ascii=True))
        emit("STATUS: READ SUCCESS")
        return
    except ImportError:
        emit("PyArrow is not installed; attempting Spark local-file reader.")
    except Exception as exc:
        emit(f"PyArrow read attempt failed: {type(exc).__name__}: {exc}")
        emit("Attempting Spark local-file reader.")

    # Use an unescaped file URI. Some Windows Hadoop builds mishandle %20
    # generated by pathlib.Path.as_uri() for directory names containing spaces.
    raw_path = path.resolve().as_posix()
    if re.match(r"^[A-Za-z]:/", raw_path):
        uri = "file:///" + raw_path
    else:
        uri = "file://" + raw_path
    emit(f"Spark URI fallback: {uri}")
    try:
        df = spark.read.parquet(uri)
        emit(f"Rows: {df.count():,}")
        emit(f"Columns: {', '.join(df.columns)}")
        for field in df.schema.fields:
            emit(f"  {field.name}: {field.dataType.simpleString()}")
        for row in df.limit(5).toJSON().collect():
            emit("  " + row)
        emit("STATUS: READ SUCCESS")
    except Exception as exc:
        emit(f"STATUS: READ FAILED - {type(exc).__name__}: {exc}")
        emit("Check the exact path, file/folder name, and whether the Parquet output exists.")

def load_results(spark):
    from pyspark.sql import types as T

    schema = T.StructType([
        T.StructField("year", T.IntegerType(), False),
        T.StructField("round", T.IntegerType(), True),
        T.StructField("event_name", T.StringType(), True),
        T.StructField("event_norm", T.StringType(), True),
        T.StructField("event_date", T.StringType(), True),
        T.StructField("driver_code", T.StringType(), True),
        T.StructField("constructor", T.StringType(), True),
        T.StructField("position", T.StringType(), True),
        T.StructField("grid", T.StringType(), True),
        T.StructField("status", T.StringType(), True),
        T.StructField("points", T.StringType(), True),
    ])

    rows = []
    section("EXISTING OFFICIAL RACE-RESULT JSON CACHES")
    for path in RACE_FILES:
        if not path.exists():
            emit(f"NOT FOUND: {path.name}")
            continue

        year_match = re.search(r"(20\d{2})", path.name)
        if not year_match:
            emit(f"SKIPPED: cannot determine season from {path.name}")
            continue
        year = int(year_match.group(1))
        with path.open("r", encoding="utf-8-sig") as f:
            obj = json.load(f)

        races = extract_races(obj)
        file_count = 0
        for race in races:
            event_name = race.get("raceName") or race.get("event_name") or race.get("name")
            try:
                round_no = int(race.get("round")) if race.get("round") is not None else None
            except (TypeError, ValueError):
                round_no = None

            results = race.get("Results") or race.get("results") or []
            for result in results:
                driver = result.get("Driver") or result.get("driver") or {}
                constructor = result.get("Constructor") or result.get("constructor") or {}
                code = driver.get("code") or driver.get("driverId") or driver.get("familyName")
                position = result.get("positionOrder")
                if position in (None, ""):
                    position = result.get("position")
                rows.append((
                    year, round_no, event_name, normalize_event(event_name), race.get("date"),
                    str(code).upper() if code else None,
                    constructor.get("name") or constructor.get("constructorId"),
                    str(position) if position is not None else None,
                    str(result.get("grid")) if result.get("grid") is not None else None,
                    result.get("status"),
                    str(result.get("points")) if result.get("points") is not None else None,
                ))
                file_count += 1
        emit(f"{path.name}: {len(races)} events, {file_count} driver-result rows")

    if not rows:
        emit("No race-result rows were loaded.")
        return None
    return spark.createDataFrame(rows, schema=schema)

def main():
    section("FOR1SIGHT V2.5.2 - PREDICTION DATA AUDIT")
    emit(f"Audit time: {datetime.now().isoformat(timespec='seconds')}")
    emit(f"Project root: {ROOT}")
    emit("Mode: READ-ONLY. No HDFS writes, no ETL rerun, no model training, no API requests.")

    spark = None
    try:
        from pyspark.sql import SparkSession, functions as F

        spark_local = ROOT / "for1sight_runtime" / "spark_local" / "prediction_audit_v2_5_2"
        spark_local.mkdir(parents=True, exist_ok=True)
        spark = (
            SparkSession.builder
            .appName("For1Sight_V2_5_2_Prediction_Audit")
            .master("local[2]")
            .config("spark.driver.memory", "3g")
            .config("spark.driver.maxResultSize", "1g")
            .config("spark.sql.shuffle.partitions", "4")
            .config("spark.local.dir", str(spark_local))
            .config("spark.hadoop.fs.defaultFS", HDFS)
            .getOrCreate()
        )
        spark.sparkContext.setLogLevel("ERROR")
        emit(f"Spark version: {spark.version}")
        emit(f"HDFS default: {HDFS}")

        for label, path in LOCAL_FILES.items():
            inspect_local_parquet(label, path, spark)

        section("HDFS SILVER LAP-TIME EVENT COVERAGE")
        laps = spark.read.parquet(SILVER_LAPS)
        emit(f"Silver lap rows: {laps.count():,}")
        event_counts = (
            laps.groupBy("year")
            .agg(
                F.countDistinct("event_name").alias("events"),
                F.countDistinct("driver_code").alias("drivers"),
                F.count("*").alias("rows")
            )
            .orderBy("year")
        )
        for row in event_counts.collect():
            emit(f"{row['year']}: {row['events']} events, {row['drivers']} drivers, {row['rows']:,} rows")

        emit("Session coverage by season:")
        sessions = (
            laps.groupBy("year", "session_type")
            .agg(
                F.countDistinct("event_name").alias("events"),
                F.count("*").alias("rows")
            )
            .orderBy("year", "session_type")
        )
        for row in sessions.collect():
            emit(f"  {row['year']} | {row['session_type']}: {row['events']} events, {row['rows']:,} rows")

        section("PRE-RACE FEATURE AGGREGATION - IN MEMORY ONLY")
        # Race session is intentionally excluded to avoid target leakage.
        base = (
            laps
            .withColumn(
                "event_norm",
                F.regexp_replace(
                    F.regexp_replace(F.lower(F.trim(F.col("event_name"))), r"\bgrand\s*prix\b", ""),
                    r"[^a-z0-9]", ""
                )
            )
            .withColumn("driver_code_norm", F.upper(F.trim(F.col("driver_code"))))
            .withColumn("session_norm", F.lower(F.trim(F.col("session_type"))))
        )
        practice_types = ["practice 1", "practice 2", "practice 3"]
        features = (
            base.groupBy("year", "event_name", "event_norm", "driver_code_norm")
            .agg(
                F.min(F.when(F.col("session_norm").isin(practice_types), F.col("time"))).alias("best_practice_lap_s"),
                F.min(F.when(F.col("session_norm") == "qualifying", F.col("time"))).alias("best_qualifying_lap_s"),
                F.min(F.when(F.col("session_norm") == "qualifying", F.col("s1"))).alias("best_quali_s1_s"),
                F.min(F.when(F.col("session_norm") == "qualifying", F.col("s2"))).alias("best_quali_s2_s"),
                F.min(F.when(F.col("session_norm") == "qualifying", F.col("s3"))).alias("best_quali_s3_s"),
                F.sum(F.when(F.col("session_norm").isin(practice_types) & F.col("time").isNotNull(), 1).otherwise(0)).alias("practice_timed_laps"),
                F.sum(F.when((F.col("session_norm") == "qualifying") & F.col("time").isNotNull(), 1).otherwise(0)).alias("qualifying_timed_laps"),
            )
        )
        emit(f"Driver-event feature rows: {features.count():,}")
        emit("Feature columns: " + ", ".join(features.columns))

        results = load_results(spark)
        if results is not None:
            section("RACE-RESULT TO PRACTICE/QUALIFYING JOIN COVERAGE")
            results = (
                results
                .withColumn("driver_code_norm", F.upper(F.trim(F.col("driver_code"))))
                .withColumn("position_num", F.col("position").cast("int"))
            )
            keys = ["year", "event_norm", "driver_code_norm"]
            duplicate_keys = results.groupBy(*keys).count().filter(F.col("count") > 1).count()
            emit(f"Duplicate result keys (season + event + driver): {duplicate_keys:,}")

            feature_cols = [
                "year", "event_norm", "driver_code_norm",
                "best_practice_lap_s", "best_qualifying_lap_s",
                "best_quali_s1_s", "best_quali_s2_s", "best_quali_s3_s",
                "practice_timed_laps", "qualifying_timed_laps"
            ]
            joined = results.join(features.select(*feature_cols), on=keys, how="left")
            total = joined.count()
            any_features = joined.filter(
                F.col("best_practice_lap_s").isNotNull() |
                F.col("best_qualifying_lap_s").isNotNull()
            ).count()
            practice_n = joined.filter(F.col("best_practice_lap_s").isNotNull()).count()
            quali_n = joined.filter(F.col("best_qualifying_lap_s").isNotNull()).count()
            numeric_pos = joined.filter(F.col("position_num").isNotNull()).count()
            winner_n = joined.filter(F.col("position_num") == 1).count()

            def pct(n, d):
                return f"{n:,} ({n/d*100:.1f}%)" if d else f"{n:,} (n/a)"

            emit(f"Official driver-result rows: {total:,}")
            emit(f"Rows with any pre-race feature: {pct(any_features, total)}")
            emit(f"Rows with practice best lap: {pct(practice_n, total)}")
            emit(f"Rows with qualifying best lap: {pct(quali_n, total)}")
            emit(f"Rows with numeric finishing position: {numeric_pos:,}")
            emit(f"Winner-labelled rows (position = 1): {winner_n:,}")

            emit("Join coverage by season:")
            by_year = (
                joined.groupBy("year")
                .agg(
                    F.count("*").alias("result_rows"),
                    F.sum(F.when(F.col("best_practice_lap_s").isNotNull(), 1).otherwise(0)).alias("practice_rows"),
                    F.sum(F.when(F.col("best_qualifying_lap_s").isNotNull(), 1).otherwise(0)).alias("quali_rows"),
                    F.sum(F.when(F.col("position_num").isNotNull(), 1).otherwise(0)).alias("position_rows")
                ).orderBy("year")
            )
            for row in by_year.collect():
                emit(
                    f"  {row['year']}: results={row['result_rows']:,}, "
                    f"practice={row['practice_rows']:,}, qualifying={row['quali_rows']:,}, "
                    f"numeric_positions={row['position_rows']:,}"
                )

            section("EVENT-NAME MATCH CHECK")
            lap_events = base.select("year", "event_norm").distinct()
            result_events = results.select("year", "event_norm", "event_name").distinct()
            unmatched = result_events.join(lap_events, on=["year", "event_norm"], how="left_anti")
            unmatched_rows = unmatched.orderBy("year", "event_name").collect()
            if unmatched_rows:
                for row in unmatched_rows:
                    emit(f"UNMATCHED: {row['year']} | {row['event_name']}")
            else:
                emit("All race-result events have a normalized event match in Silver lap-time data.")

            section("SAMPLE JOINED ROWS")
            for row in joined.select(
                "year", "event_name", "driver_code", "constructor", "position",
                "best_practice_lap_s", "best_qualifying_lap_s",
                "practice_timed_laps", "qualifying_timed_laps"
            ).limit(12).toJSON().collect():
                emit(row)

        section("INTERPRETATION")
        emit("1. Local Parquet inspection prefers PyArrow to avoid Windows Spark URI issues.")
        emit("2. The HDFS Silver lap-time dataset is the source for in-memory practice and qualifying features.")
        emit("3. Race-session lap times and race telemetry are excluded from pre-race features.")
        emit("4. The join coverage results determine whether the event/driver keys are reliable.")
        emit("5. This audit does not create a training dataset or train a model.")

    except Exception as exc:
        section("AUDIT ERROR")
        emit(f"{type(exc).__name__}: {exc}")
        emit(traceback.format_exc())
    finally:
        if spark is not None:
            try:
                spark.stop()
                emit("Spark session stopped.")
            except Exception as exc:
                emit(f"Spark stop warning: {type(exc).__name__}: {exc}")

        report_path = WAREHOUSE / "prediction_data_audit_v2_5_2.txt"
        try:
            WAREHOUSE.mkdir(parents=True, exist_ok=True)
            report_path.write_text("\n".join(REPORT) + "\n", encoding="utf-8")
            print(f"\nUTF-8 report saved to: {report_path}")
        except Exception as exc:
            print(f"\nCould not save UTF-8 report: {type(exc).__name__}: {exc}")

if __name__ == "__main__":
    main()
